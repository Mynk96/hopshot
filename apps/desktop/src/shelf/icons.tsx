export function Icon({ name, size = 14 }: { name: keyof typeof PATHS | string; size?: number }) {
  const path = PATHS[name];
  if (!path) {
    // Silently rendering nothing turns a typo into an invisible button, which is much
    // harder to spot than a missing glyph.
    console.error(`no icon named "${name}"`);
    return null;
  }

  return (
    <svg
      aria-hidden
      width={size}
      height={size}
      viewBox="0 0 24 24"
      // Icons sit in flex rows next to text that can be long; without this they squash.
      className="shrink-0"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.6}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {path}
    </svg>
  );
}
